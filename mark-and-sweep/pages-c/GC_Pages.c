void sweep_all(heap_t heap, pstate_t t)
{
  uint64_t np = (heap_size_u640 - zero_addr1) / 32768ULL;
  uint64_t p = 0ULL;
  uint64_t __anf0 = p;
  bool cond = __anf0 < np;
  while (cond)
  {
    uint64_t vp = p;
    pinfo r = read_entry(t, vp);
    if (r.swept)
      if (r.code == 2U && r.arg > 0ULL)
        p = vp + r.arg;
      else
        p = vp + 1ULL;
    else if (r.code == 1U && r.arg < 31ULL)
    {
      pool_step(heap, t, vp, r);
      p = vp + 1ULL;
    }
    else if (r.code == 2U && r.arg > 0ULL)
    {
      run_step(heap, t, vp, r);
      p = vp + r.arg;
    }
    else
      p = vp + 1ULL;
    uint64_t __anf0 = p;
    cond = __anf0 < np;
  }
}

void sweep(heap_t heap, pstate_t t)
{
  start_sweep(t);
  sweep_all(heap, t);
}

