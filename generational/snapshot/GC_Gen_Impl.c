uint64_t init_heap(heap_t heap)
{
  uint64_t total_words = heap_size_u640 / 8ULL;
  if (total_words < 2ULL)
    return 0ULL;
  else
  {
    uint64_t wz = total_words - 1ULL;
    uint64_t hdr = makeHeader(wz, blue, 0ULL);
    write_word(heap, zero_addr1, hdr);
    write_word(heap, 8ULL, 0ULL);
    return 8ULL;
  }
}

static bool is_valid_fp(uint64_t v)
{
  return v >= zero_addr1 + 8ULL && v < heap_size_u640 && v % 8ULL == 0ULL;
}

uint64_t
allocate(heap_t heap, uint64_t *fp_ref, phase_state *phase, uint64_t wosize, uint64_t tag)
{
  uint64_t fp = *fp_ref;
  phase_state pv = *phase;
  uint64_t head_fp = fp;
  uint64_t prev_fp = 0ULL;
  uint64_t cur_fp = fp;
  uint64_t result_obj = 0ULL;
  bool go = true;
  uint64_t fuel_ref = heap_size_u640 / 8ULL;
  while (go)
  {
    uint64_t vfuel = fuel_ref;
    if (vfuel == 0ULL)
      go = false;
    else
    {
      uint64_t vcur = cur_fp;
      bool valid = is_valid_fp(vcur);
      if (!valid)
        go = false;
      else
      {
        uint64_t hd_addr = hd_address(vcur);
        uint64_t hdr = read_word(heap, hd_addr);
        uint64_t block_wz = getWosize(hdr);
        uint64_t next = read_word(heap, vcur);
        if (block_wz >= wosize)
        {
          uint64_t leftover = block_wz - wosize;
          uint64_t vp = prev_fp;
          uint64_t alloc_hd_off = hd_addr + leftover * 8ULL;
          uint64_t alloc_obj = alloc_hd_off + 8ULL;
          if (alloc_obj >= heap_size_u640)
            go = false;
          else
          {
            if (pv.ps_kind == 1ULL && vcur == pv.ps_swept_tail && leftover < 2ULL)
              phase->ps_swept_tail = vp;
            bool b = pv.ps_kind != 0ULL && (pv.ps_kind != 1ULL || alloc_hd_off >= pv.ps_cursor);
            color_sem col = b ? black : white;
            if (leftover >= 1ULL)
            {
              uint64_t new_fp = leftover >= 2ULL ? vcur : next;
              bool vp_unusable = vp == 0ULL || vp == hd_addr;
              if (vp_unusable)
              {
                uint64_t rem_hdr = makeHeader(leftover - 1ULL, blue, 0ULL);
                write_word(heap, hd_addr, rem_hdr);
                uint64_t alloc_hdr = makeHeader(wosize, col, tag);
                write_word(heap, alloc_hd_off, alloc_hdr);
                head_fp = new_fp;
                result_obj = alloc_obj;
                go = false;
              }
              else
              {
                write_word(heap, vp, new_fp);
                uint64_t rem_hdr = makeHeader(leftover - 1ULL, blue, 0ULL);
                write_word(heap, hd_addr, rem_hdr);
                uint64_t alloc_hdr = makeHeader(wosize, col, tag);
                write_word(heap, alloc_hd_off, alloc_hdr);
                result_obj = alloc_obj;
                go = false;
              }
            }
            else
            {
              bool vp_unusable = vp == 0ULL || vp == hd_addr;
              if (vp_unusable)
              {
                uint64_t alloc_hdr = makeHeader(wosize, col, tag);
                write_word(heap, hd_addr, alloc_hdr);
                head_fp = next;
                result_obj = alloc_obj;
                go = false;
              }
              else
              {
                write_word(heap, vp, next);
                uint64_t alloc_hdr = makeHeader(wosize, col, tag);
                write_word(heap, hd_addr, alloc_hdr);
                result_obj = alloc_obj;
                go = false;
              }
            }
          }
        }
        else
        {
          prev_fp = vcur;
          cur_fp = next;
          fuel_ref = vfuel - 1ULL;
        }
      }
    }
  }
  uint64_t final_fp = head_fp;
  uint64_t final_obj = result_obj;
  *fp_ref = final_fp;
  return final_obj;
}

